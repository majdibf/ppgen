package com.pptxgenerator.model;

public class ThemeFonts {
    private FontStyle title;
    private FontStyle subtitle;
    private FontStyle body;
    private FontStyle caption;

    public FontStyle getTitle() { return title; }
    public void setTitle(FontStyle title) { this.title = title; }

    public FontStyle getSubtitle() { return subtitle; }
    public void setSubtitle(FontStyle subtitle) { this.subtitle = subtitle; }

    public FontStyle getBody() { return body; }
    public void setBody(FontStyle body) { this.body = body; }

    public FontStyle getCaption() { return caption; }
    public void setCaption(FontStyle caption) { this.caption = caption; }
}
